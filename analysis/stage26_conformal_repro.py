"""Rebuild the conformal calibration from per-case predictions, with a reproducible split.

The archived file gives one constant half-width for all 256 cases, so per-fold coverage varies with the
fold's residual distribution while the pooled figure looks nominal. This script recomputes split
conformal properly: the score is |y_true - pred|, the quantile is taken on the cases that are not being
scored, and the split is generated by a seeded, stratified assignment that anyone can reproduce.
"""
import csv
import json
import math
import os
import random
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = _HERE
while not os.path.exists(os.path.join(_ROOT, "paths.py")) and os.path.dirname(_ROOT) != _ROOT:
    _ROOT = os.path.dirname(_ROOT)
sys.path.insert(0, _ROOT)
from paths import ARTEFACTS, OUT, record  # noqa: E402
import statistics as st

HERE = os.path.dirname(os.path.abspath(__file__))
ROWS = record("A1_A2_Closure_Calibration/conformal_rows.csv")
OUT = os.path.join(HERE, "stage26_conformal")
LEVEL = 0.90


def quantile(scores, level):
    """Finite-sample split-conformal quantile: the ceil((n+1)*level)-th smallest score."""
    s = sorted(scores)
    k = math.ceil((len(s) + 1) * level)
    return s[min(k, len(s)) - 1]


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0)
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    r = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return ((c - r) / d, (c + r) / d)


def coverage(cases, q):
    hit = sum(1 for c in cases if abs(c["y_true"] - c["pred"]) <= q)
    return hit, len(cases)


def main():
    rows = [dict(case=int(r["case_id"]), fold=int(r["fold"]), y_true=float(r["y_true"]),
                 pred=float(r["pred"])) for r in csv.DictReader(open(ROWS))]
    n = len(rows)
    scores = [abs(c["y_true"] - c["pred"]) for c in rows]
    out = {"n": n, "level": LEVEL, "score": "absolute residual"}

    # A. the archived artefact: one constant half-width for every case
    out["archived"] = {"half_width": 0.37647,
                       "pooled_coverage": coverage(rows, 0.37647)[0] / n,
                       "per_fold": {}}
    for f in sorted({c["fold"] for c in rows}):
        g = [c for c in rows if c["fold"] == f]
        out["archived"]["per_fold"][str(f)] = {"n": len(g), "coverage": coverage(g, 0.37647)[0] / len(g)}

    # B. pooled quantile, recomputed (what a single global threshold achieves by construction)
    q_pool = quantile(scores, LEVEL)
    hit, tot = coverage(rows, q_pool)
    lo, hi = wilson(hit, tot)
    out["pooled_quantile"] = {"q": q_pool, "coverage": hit / tot, "wilson95": [lo, hi]}

    # C. leave-one-fold-out: the quantile never sees the cases it is scored on
    lofo_hits, lofo_tot, per_fold = 0, 0, {}
    for f in sorted({c["fold"] for c in rows}):
        cal = [abs(c["y_true"] - c["pred"]) for c in rows if c["fold"] != f]
        test = [c for c in rows if c["fold"] == f]
        q = quantile(cal, LEVEL)
        hit, tot = coverage(test, q)
        per_fold[str(f)] = {"n": tot, "q": q, "coverage": hit / tot}
        lofo_hits += hit
        lofo_tot += tot
    lo, hi = wilson(lofo_hits, lofo_tot)
    out["leave_one_fold_out"] = {"coverage": lofo_hits / lofo_tot, "wilson95": [lo, hi], "per_fold": per_fold}

    # D. repeated stratified four-fold, seeded, stratifying on the true value
    order = sorted(rows, key=lambda c: c["y_true"])
    strata = [order[i::4] for i in range(4)]
    repeats, k_folds = 20, 4
    seeds, coverages, widths = [], [], []
    for seed in range(repeats):
        rng = random.Random(seed)
        assign = {}
        for quartile in range(4):
            group = [order[i] for i in range(len(order)) if i % 4 == quartile]
            rng.shuffle(group)
            for i, c in enumerate(group):
                assign[c["case"]] = i % k_folds
        hits = tot = 0
        for f in range(k_folds):
            cal = [abs(c["y_true"] - c["pred"]) for c in rows if assign[c["case"]] != f]
            test = [c for c in rows if assign[c["case"]] == f]
            q = quantile(cal, LEVEL)
            h, t = coverage(test, q)
            hits += h
            tot += t
        coverages.append(hits / tot)
        widths.append(quantile([abs(c["y_true"] - c["pred"]) for c in rows[:n - n // k_folds]], LEVEL))
    out["repeated_stratified_4fold"] = {
        "repeats": repeats, "seeds": list(range(repeats)),
        "mean_coverage": st.mean(coverages), "sd": st.pstdev(coverages),
        "min": min(coverages), "max": max(coverages),
        "wilson95_at_mean": wilson(round(st.mean(coverages) * n), n),
        "coverage_per_seed": coverages,
    }
    # E. per-stratum coverage at the pooled quantile: does the interval hold across the domain?
    quart = sorted(range(n), key=lambda i: rows[i]["y_true"])
    per_q = {}
    for b in range(4):
        idx = quart[b * n // 4:(b + 1) * n // 4]
        g = [rows[i] for i in idx]
        hit, tot = coverage(g, q_pool)
        per_q[str(b)] = {"n": tot, "coverage": hit / tot,
                         "y_true_range": [min(c["y_true"] for c in g), max(c["y_true"] for c in g)]}
    out["coverage_by_true_quartile"] = per_q

    # the split itself ships with the package: seed -> fold for every case, so a reader can rebuild the
    # coverage without rerunning the generator
    splits = {}
    for seed in range(repeats):
        rng = random.Random(seed)
        assign = {}
        for quartile in range(4):
            group = [order[i] for i in range(len(order)) if i % 4 == quartile]
            rng.shuffle(group)
            for i, c in enumerate(group):
                assign[c["case"]] = i % k_folds
        splits[str(seed)] = {str(k): v for k, v in sorted(assign.items())}
    os.makedirs(OUT, exist_ok=True)
    json.dump(splits, open(os.path.join(OUT, "conformal_split.json"), "w"))
    out["split_file"] = "conformal_split.json (seed -> case -> fold)"
    json.dump(out, open(os.path.join(OUT, "conformal_repro.json"), "w"), indent=1)
    print("n=%d  pooled q=%.4f cov=%.3f  LOFO cov=%.3f [%.3f,%.3f]" %
          (n, q_pool, out["pooled_quantile"]["coverage"], out["leave_one_fold_out"]["coverage"],
           *out["leave_one_fold_out"]["wilson95"]))
    print("repeated stratified 4-fold: %.3f +- %.3f (min %.3f, max %.3f)" %
          (st.mean(coverages), st.pstdev(coverages), min(coverages), max(coverages)))
    print("quartile coverage:", {k: round(v["coverage"], 3) for k, v in per_q.items()})


if __name__ == "__main__":
    main()
